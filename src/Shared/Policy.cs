using System;
using Microsoft.Win32;

namespace StayAwake.Shared
{
    /// <summary>
    /// Admin settings. The MSI writes them to HKLM\SOFTWARE\Policies\StayAwake,
    /// so they can also be set or overridden later with Group Policy Preferences.
    /// Missing or invalid values fall back to the defaults below.
    /// </summary>
    public sealed class Policy
    {
        public const string PolicyKeyPath = @"SOFTWARE\Policies\StayAwake";

        /// <summary>Minutes with no keyboard or mouse input before the session locks.</summary>
        public int IdleLockMinutes = 10;

        /// <summary>Longest grace period a user may start, in minutes.</summary>
        public int MaxGraceMinutes = 60;

        /// <summary>Hotkey that opens the window, e.g. "Ctrl+Alt+S" or "Win+Alt+K". "None" disables it.</summary>
        public string Hotkey = "Ctrl+Alt+S";

        /// <summary>True: recent durations and end times are shared by everyone on the PC. False: per user.</summary>
        public bool MachineHistory;

        /// <summary>
        /// Who may start a grace period. Empty means everyone. Otherwise one or more
        /// groups or users separated by semicolons: "DOMAIN\Staff", "Teachers" (local group), or a SID.
        /// </summary>
        public string AllowedGroup = "";

        /// <summary>When true, keyboard and mouse input generated by software (jigglers, SendInput) does not count as activity.</summary>
        public bool IgnoreInjectedInput;

        public static Policy Load()
        {
            var p = new Policy();
            try
            {
                using (var hklm = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64))
                using (var key = hklm.OpenSubKey(PolicyKeyPath))
                {
                    if (key == null) return p;
                    p.IdleLockMinutes = Clamp(ReadInt(key, "IdleLockMinutes", p.IdleLockMinutes), 1, 1440);
                    p.MaxGraceMinutes = Clamp(ReadInt(key, "MaxGraceMinutes", p.MaxGraceMinutes), 1, 1440);
                    p.Hotkey = ReadString(key, "Hotkey", p.Hotkey);
                    p.MachineHistory = string.Equals(ReadString(key, "HistoryScope", "User"), "Machine", StringComparison.OrdinalIgnoreCase);
                    p.AllowedGroup = ReadString(key, "AllowedGroup", "").Trim();
                    p.IgnoreInjectedInput = ReadInt(key, "IgnoreInjectedInput", 0) != 0;
                }
            }
            catch
            {
                // Unreadable policy: keep defaults. Defaults still enforce the idle lock.
            }
            return p;
        }

        static int Clamp(int v, int lo, int hi) { return v < lo ? lo : (v > hi ? hi : v); }

        static int ReadInt(RegistryKey key, string name, int fallback)
        {
            object v = key.GetValue(name);
            if (v is int i) return i;
            if (v is string s && int.TryParse(s.Trim(), out int parsed)) return parsed;
            return fallback;
        }

        static string ReadString(RegistryKey key, string name, string fallback)
        {
            object v = key.GetValue(name);
            if (v == null) return fallback;
            string s = Convert.ToString(v);
            return s == null ? fallback : s;
        }
    }
}
